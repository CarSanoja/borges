"""Summarise a batch of live repeat runs as Markdown.

Every run JSON in DIR is one `borges run --json` output named <case>-<i>.json. The report gives the
completion rate with a Wilson interval, the verdicts and flip rate per case, adversary flips,
failed universes, cost, self-corrections, every completed run that lost universes, options or a
stage, and every run that did not complete.

Usage: uv run python scripts/repeats_report.py DIR --commit SHA --date YYYY-MM-DD [--out FILE]
"""

from __future__ import annotations

import argparse
import json
import math
import re
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

LOST = re.compile(
    r"left out of the analysis|stage failed and was skipped|"
    r"failed its smoke run and was replaced by|was dropped: with it|"
    r"failed its smoke run and is not in the analysis"
)


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return 0.0, 0.0
    p = k / n
    d = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / d
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, centre - half), min(1.0, centre + half)


def load_run(path: Path) -> dict[str, Any]:
    try:
        run = json.loads(path.read_text())
    except ValueError:
        return {"status": "unreadable", "run": path.name, "error": "unreadable JSON"}
    report = run.get("report") or {}
    steps = (run.get("plan") or {}).get("steps", [])
    origin = {o["id"]: o.get("origin") or "planner" for s in steps for o in s["options"]}
    changes = (report.get("minimal_flip") or {}).get("changes") or []
    coding = report.get("coding") or {}
    return {
        "status": run.get("status"),
        "run": run.get("run_id"),
        "verdict": report.get("original_verdict"),
        "flip": bool(changes),
        "flip_steps": " + ".join(
            sorted(c.get("step_title") or c.get("step_id") or "?" for c in changes)
        ),
        "adversary": any(origin.get(c.get("to_option")) == "adversary" for c in changes),
        "universes": report.get("n_universes") or 0,
        "failed": report.get("n_failed") or 0,
        "cost": (run.get("usage") or {}).get("cost_usd"),
        "error": run.get("error"),
        "recoded": coding.get("options_recoded_by_output_check") or 0,
        "repaired": coding.get("repaired_after_smoke") or 0,
        "replanned": coding.get("replanned_steps") or 0,
        "lost": [c for c in report.get("caveats") or [] if LOST.search(c)],
    }


def load_batch(directory: Path) -> dict[str, list[dict[str, Any]]]:
    rows: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for path in sorted(directory.glob("*.json")):
        rows[path.stem.rsplit("-", 1)[0]].append(load_run(path))
    return dict(rows)


def _case_row(label: str, runs: list[dict[str, Any]]) -> str:
    done = [r for r in runs if r["status"] == "completed"]
    flips = [r for r in done if r["flip"]]
    low, high = wilson(len(flips), len(done))
    verdicts = ", ".join(f"{v} ×{n}" for v, n in Counter(r["verdict"] for r in done).most_common())
    costs = [r["cost"] for r in done if r["cost"] is not None]
    mean = sum(costs) / len(costs) if costs else 0.0
    rate = len(flips) / len(done) if done else 0.0
    steps = "; ".join(f"{t} ×{n}" for t, n in Counter(r["flip_steps"] for r in flips).most_common())
    return (
        f"| {label} | {len(done)}/{len(runs)} | {verdicts} | {len(flips)}/{len(done)} | "
        f"{rate:.0%} ({low:.2f}–{high:.2f}) | {sum(r['adversary'] for r in flips)} | "
        f"{steps or '—'} | "
        f"{sum(r['universes'] for r in done)} ({sum(r['failed'] for r in done)}) | ${mean:.3f} |"
    )


def _partial(rows: dict[str, list[dict[str, Any]]]) -> list[str]:
    lines = []
    for label, batch in sorted(rows.items()):
        for r in batch:
            if r["status"] != "completed":
                continue
            tried = r["universes"] + r["failed"]
            notes = [f"{r['failed']} of {tried} universes failed"] if r["failed"] else []
            notes += [c[:240] for c in r["lost"]]
            if notes:
                lines.append(f"- {label} `{r['run']}`: " + " ".join(notes))
    return lines or ["None."]


def render(rows: dict[str, list[dict[str, Any]]], commit: str, date: str) -> str:
    runs = [r for batch in rows.values() for r in batch]
    done = [r for r in runs if r["status"] == "completed"]
    low, high = wilson(len(done), len(runs))
    cost = sum(r["cost"] or 0 for r in done)
    lines = [
        "# Live repeats",
        "",
        f"Every case was run five times live at commit `{commit}` on {date}, each from an empty "
        "LLM cache and an empty Borges home, on Nemotron through Nebius Token Factory with ConTree "
        "sandboxes (`borges run --case X --llm nebius --backend contree --json`). The checkout "
        "case also runs blind (`--blind-notes`). Generated by `scripts/repeats_report.py` from "
        "the run JSON files; see `evidence/census.md` for every failure found per commit.",
        "",
        f"**Runs completed: {len(done)} of {len(runs)}** (95% Wilson interval {low:.2f} to "
        f"{high:.2f}). Cost of the completed runs: ${cost:.2f}.",
        "",
        "| case | completed | verdicts | flip found | flip rate (95% CI) | adversary flips "
        "| decision that flips | universes run (failed) | cost per run |",
        "|---|---|---|---|---|---|---|---|---|",
        *(_case_row(label, batch) for label, batch in sorted(rows.items())),
        "",
        "A flip is a defensible change of analysis choices that reverses the verdict; the flip "
        "rate is how often a run finds one. The planner picks the original analysis anew in every "
        "run, so the original verdict can differ between runs; the decision that flips it is the "
        "finding to compare.",
        "",
        "## Self-corrections",
        "",
        f"- options recoded because their output failed a check: {sum(r['recoded'] for r in done)}",
        f"- options repaired after the smoke stage: {sum(r['repaired'] for r in done)}",
        f"- steps re-planned after every option failed: {sum(r['replanned'] for r in done)}",
        "",
        "## Completed runs that lost part of the analysis",
        "",
        *_partial(rows),
        "",
        "## Runs that did not complete",
        "",
    ]
    missing = [(label, r) for label, batch in sorted(rows.items()) for r in batch if r not in done]
    lines += [f"- {label} `{r['run']}`: {str(r['error'])[:300]}" for label, r in missing] or [
        "None."
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("dir", type=Path)
    parser.add_argument("--commit", required=True)
    parser.add_argument("--date", required=True)
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    text = render(load_batch(args.dir), args.commit, args.date)
    if args.out is None:
        print(text, end="")
    else:
        args.out.write_text(text)


if __name__ == "__main__":
    main()
